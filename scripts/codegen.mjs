// pnpm codegen (addendum O1). Steps 1-2: Sentinel Protocol schemas -> Pydantic models and TypeScript types.
// Output is committed and must be deterministic (no timestamps). Paths contain spaces: never use a shell string.
import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const protocolDir = join(root, "packages", "protocol");
const schemasDir = join(protocolDir, "schemas");

function run(cmd, args) {
  const r = spawnSync(cmd, args, { cwd: root, stdio: "inherit", shell: false });
  if (r.error) throw r.error;
  if (r.status !== 0) {
    console.error(`codegen: ${cmd} exited with status ${r.status}`);
    process.exit(r.status ?? 1);
  }
}

// Step 1: datamodel-code-generator (Pydantic v2).
const pyOut = join(protocolDir, "src", "bcs_protocol", "generated");
rmSync(pyOut, { recursive: true, force: true });
run("uv", [
  "run",
  "datamodel-codegen",
  "--input", schemasDir,
  "--input-file-type", "jsonschema",
  "--output-model-type", "pydantic_v2.BaseModel",
  "--output", pyOut,
  "--use-annotated",
  "--field-constraints",
  "--disable-timestamp",
  "--collapse-root-models",
  "--enum-field-as-literal", "all",
]);

// Step 2: json-schema-to-typescript, one file per schema.
const require = createRequire(join(protocolDir, "package.json"));
const { compileFromFile } = await import(pathToFileURL(require.resolve("json-schema-to-typescript")).href);
const tsOut = join(protocolDir, "ts", "generated");
rmSync(tsOut, { recursive: true, force: true });
mkdirSync(tsOut, { recursive: true });
const schemas = readdirSync(schemasDir).filter((f) => f.endsWith(".schema.json")).sort();
for (const file of schemas) {
  const ts = await compileFromFile(join(schemasDir, file), {
    cwd: schemasDir,
    bannerComment: "/* Generated by scripts/codegen.mjs from packages/protocol/schemas. Do not edit. */",
    additionalProperties: false,
    strictIndexSignatures: false,
  });
  writeFileSync(join(tsOut, file.replace(/\.json$/, ".ts")), ts, "utf8");
}
console.log(`codegen: protocol done (${schemas.length} schemas)`);

// Steps 3-5 (addendum O1): Ground Station OpenAPI + event schema -> @bcs/api-types.
const apiDir = join(root, "packages", "api-types");
run("uv", ["run", "bcs-gs", "export-openapi", "--out", join(apiDir, "openapi.json")]);
run("uv", ["run", "bcs-gs", "export-event-schemas", "--out", join(apiDir, "events.schema.json")]);

const apiRequire = createRequire(join(apiDir, "package.json"));
const apiGen = join(apiDir, "src", "generated");
rmSync(apiGen, { recursive: true, force: true });
mkdirSync(apiGen, { recursive: true });
const ots = await import(pathToFileURL(apiRequire.resolve("openapi-typescript")).href);
const openapiTs = typeof ots.default === "function" ? ots.default : ots.default?.default ?? ots.default?.openapiTS ?? ots.openapiTS;
const astToString = ots.astToString;
const ast = await openapiTs(pathToFileURL(join(apiDir, "openapi.json")));
writeFileSync(
  join(apiGen, "openapi.ts"),
  "/* Generated by scripts/codegen.mjs from packages/api-types/openapi.json. Do not edit. */\n" +
    astToString(ast).replace(/\r\n/g, "\n"),
  "utf8",
);
const j2t = await import(pathToFileURL(apiRequire.resolve("json-schema-to-typescript")).href);
const evTs = await j2t.compileFromFile(join(apiDir, "events.schema.json"), {
  cwd: apiDir,
  bannerComment: "/* Generated by scripts/codegen.mjs from packages/api-types/events.schema.json. Do not edit. */",
  additionalProperties: false,
  strictIndexSignatures: false,
});
writeFileSync(join(apiGen, "events.ts"), evTs.replace(/\r\n/g, "\n"), "utf8");
console.log("codegen: api-types done");
