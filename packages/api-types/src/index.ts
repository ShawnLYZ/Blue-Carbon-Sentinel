/** Any event the Ground Station can send on /ws/events (addendum J2). */
export type AnyEvent = GeneratedEvent
export type EventType = NonNullable<AnyEvent['type']>
/** Event type -> its `data` payload. */
export type EventMap = { [E in AnyEvent as NonNullable<E['type']>]: E['data'] }

/** Wire envelope. Generic for consumers that narrow `data`. */
export interface EventEnvelope<T = unknown> {
  v: 1
  type: string
  id: string
  at: string
  data: T
}
